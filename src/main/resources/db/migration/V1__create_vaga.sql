CREATE TABLE vaga (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    empresa VARCHAR(255) NOT NULL,
    url TEXT NOT NULL,
    descricao TEXT,
    status VARCHAR(255) NOT NULL DEFAULT 'NOVA',
    data_coleta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_vaga_url UNIQUE (url),
    CONSTRAINT ck_vaga_status CHECK (status IN ('NOVA', 'ANALISADA', 'DESCARTADA'))
);
